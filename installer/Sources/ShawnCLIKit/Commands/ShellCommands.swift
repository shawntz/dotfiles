import Foundation

struct ShellInitCommand: BuiltinCommand {
    let name = "shell-init"
    let section = BuiltinSection.shell
    let summary = "Shell integration: completion, sd, cd after clone/new"
    let usage = "zsh"
    let details: String? = "Add to ~/.zshrc: command -v shawn >/dev/null && eval \"$(shawn shell-init zsh)\". It only defines functions; nothing runs and nothing is written."

    func run(_ arguments: [String], context: CLIContext) async -> Int32 {
        let (parsed, code) = parse(arguments, context: context)
        guard let parsed else { return code }
        guard parsed.positionals == ["zsh"] else {
            context.fail("shawn shell-init: only zsh is supported (shawn shell-init zsh)")
            return ExitCode.usage
        }
        context.out.write(Self.zsh)
        return ExitCode.ok
    }

    static let zsh = #"""
    # shawn shell integration (from `shawn shell-init zsh`). Defines functions only.

    # Completion: the installer writes _shawn into ~/.local/share/zsh/site-functions.
    () {
      local dir="$HOME/.local/share/zsh/site-functions"
      [[ -d $dir ]] || return 0
      (( ${fpath[(Ie)$dir]} )) || fpath=("$dir" $fpath)
      if (( $+functions[compdef] )) && [[ -r $dir/_shawn ]]; then
        autoload -Uz _shawn && compdef _shawn shawn
      fi
    }

    # sd [query]: jump to a git project in ~/Developer, picked with fzf.
    sd() {
      local root="${SHAWN_DEVELOPER_DIR:-$HOME/Developer}" pick
      if (( ! $+commands[fzf] )); then
        print -u2 "sd: needs fzf (brew install fzf)"
        return 1
      fi
      local -a repos
      repos=( "$root"/*/.git(N:h) "$root"/*/*/.git(N:h) )
      if (( ${#repos} == 0 )); then
        print -u2 "sd: no git repositories in $root"
        return 1
      fi
      pick=$(print -rl -- "${repos[@]#$root/}" | fzf --height=40% --reverse --prompt='project> ' --query="$*" --select-1 --exit-0) || return
      [[ -n $pick ]] && cd -- "$root/$pick"
    }

    # `shawn clone` and `shawn new` leave you in the new directory.
    shawn() {
      if [[ $1 == clone || $1 == new ]]; then
        local cdfile target rc
        cdfile=$(mktemp -t shawn-cd) || { command shawn "$@"; return; }
        SHAWN_CD_FILE=$cdfile command shawn "$@"
        rc=$?
        target=$(<"$cdfile")
        command rm -f -- "$cdfile"
        [[ $rc -eq 0 && -n $target && -d $target ]] && cd -- "$target"
        return $rc
      fi
      command shawn "$@"
    }

    """#
}

struct CompletionsCommand: BuiltinCommand {
    let name = "completions"
    let section = BuiltinSection.shell
    let summary = "Print the zsh completion script"
    let usage = "zsh"

    func run(_ arguments: [String], context: CLIContext) async -> Int32 {
        let (parsed, code) = parse(arguments, context: context)
        guard let parsed else { return code }
        guard parsed.positionals == ["zsh"] else {
            context.fail("shawn completions: only zsh is supported (shawn completions zsh)")
            return ExitCode.usage
        }
        context.out.write(Self.zsh(builtins: Builtins.all, commands: context.cli.commands))
        return ExitCode.ok
    }

    /// The `_shawn` completion function: every command with its summary, the fixed options of the
    /// built-ins, and the wrapped tool's own completion after `shawn claude` and friends.
    static func zsh(builtins: [any BuiltinCommand], commands: [CLIConfig.Command]) -> String {
        let builtinNames = Set(builtins.flatMap { [$0.name] + $0.aliases })
        var entries: [(String, String)] = []
        for command in commands where !builtinNames.contains(command.name) {
            entries.append((command.name, command.summary))
        }
        for command in builtins where !command.name.hasPrefix("_") {
            entries.append((command.name, command.summary))
            for alias in command.aliases { entries.append((alias, command.summary)) }
        }

        var lines = [
            "#compdef shawn",
            "# zsh completion for shawn, generated by `shawn completions zsh`. Regenerate it rather than editing.",
            "",
            "_shawn() {",
            "  local curcontext=\"$curcontext\" state line",
            "  local -a commands",
            "  commands=(",
        ]
        for (name, summary) in entries {
            lines.append("    \(quote(name.replacingOccurrences(of: ":", with: "\\:") + ":" + summary))")
        }
        lines.append("  )")
        lines.append("  _arguments -C \\")
        for option in Dispatcher.globalOptions {
            lines.append("    \(optionSpec(option)) \\")
        }
        lines += [
            "    '1: :->command' \\",
            "    '*:: :->args'",
            "  case $state in",
            "    command)",
            "      _describe -t commands 'shawn command' commands",
            "      ;;",
            "    args)",
            "      case $words[1] in",
        ]
        for command in builtins where !command.name.hasPrefix("_") {
            let patterns = ([command.name] + command.aliases).joined(separator: "|")
            lines.append("        \(patterns))")
            if command.name == "help" {
                lines.append("          _describe -t commands 'shawn command' commands")
            } else {
                var specs = command.options.map(optionSpec)
                if !command.subcommands.isEmpty {
                    specs.append(quote("1:action:(" + command.subcommands.map(\.name).joined(separator: " ") + ")") + " '*:file:_files'")
                } else if command.usage.hasPrefix("zsh") {
                    specs.append("'1:shell:(zsh)'")
                } else {
                    specs.append("'*:file:_files'")
                }
                lines.append("          _arguments -s \\")
                lines.append(specs.map { "            " + $0 }.joined(separator: " \\\n"))
            }
            lines.append("          ;;")
        }
        for command in commands where !builtinNames.contains(command.name) {
            lines.append("        \(command.name))")
            if case .exec(let parts) = command.action, case .text(let program)? = parts.first {
                // Hand over to the tool's own completion, as if it had been typed directly.
                lines.append("          words[1]=\(quote(program)); _normal")
            } else {
                lines.append("          _default")
            }
            lines.append("          ;;")
        }
        lines += [
            "        *)",
            "          _default",
            "          ;;",
            "      esac",
            "      ;;",
            "  esac",
            "}",
            "",
            "_shawn \"$@\"",
            "",
        ]
        return lines.joined(separator: "\n")
    }

    static func optionSpec(_ option: OptionSpec) -> String {
        let help = option.help.replacingOccurrences(of: "[", with: "\\[").replacingOccurrences(of: "]", with: "\\]")
        let action: String
        if let value = option.value {
            let completer = ["DIR", "PATH"].contains(value) ? "_files -/" : " "
            action = ":\(value.lowercased()):\(completer)"
        } else {
            action = ""
        }
        if let short = option.short {
            return quote("(-\(short) --\(option.name))") + "{-\(short),--\(option.name)}" + quote("[\(help)]\(action)")
        }
        return quote("--\(option.name)[\(help)]\(action)")
    }

    /// Single-quoted for zsh.
    static func quote(_ text: String) -> String {
        "'" + text.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
